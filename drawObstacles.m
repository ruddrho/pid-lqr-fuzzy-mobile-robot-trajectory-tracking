function handles = drawObstacles(ax,env)
%DRAWOBSTACLES Draw fixed circular and rectangular obstacles.
% This implementation avoids the unsupported Rectangle DisplayName
% property so it remains compatible with older MATLAB releases.

handles = gobjects(0);

for i = 1:size(env.rectangleObstacles,1)
    r = env.rectangleObstacles(i,:);
    h = rectangle(ax,'Position',r, ...
        'FaceColor',[0.24 0.24 0.28], ...
        'EdgeColor',[0.08 0.08 0.10], ...
        'LineWidth',1.3, ...
        'HandleVisibility','off');
    handles(end+1) = h; %#ok<AGROW>
end

for i = 1:size(env.circleObstacles,1)
    c = env.circleObstacles(i,:);
    h = rectangle(ax, ...
        'Position',[c(1)-c(3),c(2)-c(3),2*c(3),2*c(3)], ...
        'Curvature',[1 1], ...
        'FaceColor',[0.24 0.24 0.28], ...
        'EdgeColor',[0.08 0.08 0.10], ...
        'LineWidth',1.3, ...
        'HandleVisibility','off');
    handles(end+1) = h; %#ok<AGROW>
end
end
